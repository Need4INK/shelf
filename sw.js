// Shelf service worker: always try the network first for the app itself,
// so every launch gets the newest version; fall back to the saved copy offline.
const CACHE = 'shelf-v1';

self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', e => e.waitUntil(self.clients.claim()));

self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);

  // App files (same site): network first, bypassing the browser cache
  if (url.origin === location.origin) {
    e.respondWith(
      fetch(req, { cache: 'no-store' })
        .then(res => { const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); return res; })
        .catch(() => caches.match(req, { ignoreSearch: true }))
    );
    return;
  }

  // Scanner library (pinned version, never changes): cache first, so scanning works offline
  if (url.hostname === 'unpkg.com') {
    e.respondWith(
      caches.match(req).then(hit => hit || fetch(req).then(res => {
        const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); return res;
      }))
    );
  }
  // Everything else (book lookups, covers): straight to the network
});
